# -*- coding: utf-8 -*-
"""Географические кластеры внутри региона.

Зачем. В Юго-востоке 32 из 83 заявок — Кашира (91 км от офиса на Бирюлёвской),
Ступино и Домодедово. Если все бригады стартуют из офиса, солвер мотает их
Москва<->Кашира и суммарный пробег вырастает с 273 км до 1136 км.

Кашира и Ступино — ОДИН кластер. Это не догадка: в контрольном распределении
бригада Козырь обслуживает оба города (5 заявок Кашира + 4 Ступино), и ни одна
из 12 бригад не смешивает Москву с областью. Мы восстанавливаем структуру,
которая реально существует.
"""
CL_MOSCOW = "Москва"
CL_KASHIRA = "Кашира-Ступино"
CL_DOMODEDOVO = "Домодедово"

_KASHIRA_KEYS = ("кашира", "ступино")
_DOMODEDOVO_KEYS = ("домодедово", "востряково")

# Стартовые точки удалённых кластеров. Q&A: «для бригад, обслуживающих удалённые
# города Подмосковья, можно самостоятельно определить стартовую точку в
# соответствующем городе; такую точку предлагается считать "домом" исполнителя;
# использование фактических GPS-координат не требуется».
HOME_DEPOTS = {
    CL_KASHIRA:    dict(name="Дом бригады, Кашира",     lat=54.8375, lon=38.1678),
    CL_DOMODEDOVO: dict(name="Дом бригады, Домодедово", lat=55.4402, lon=37.7659),
}


def classify_cluster(address: str, district: str = "") -> str:
    s = ((address or "") + " " + (district or "")).lower()
    if any(k in s for k in _KASHIRA_KEYS):
        return CL_KASHIRA
    if any(k in s for k in _DOMODEDOVO_KEYS):
        return CL_DOMODEDOVO
    return CL_MOSCOW


def clean_district(district: str) -> str:
    """Поле «Район» местами содержит технологию, а не географию.
    Пример: «GPON Даниловский» — это не отдельный район, а тип сети."""
    d = (district or "").strip()
    for tech in ("GPON ", "FTTB ", "FMC "):
        if d.startswith(tech):
            return d[len(tech):].strip()
    return d
