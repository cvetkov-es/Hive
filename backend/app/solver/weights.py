# -*- coding: utf-8 -*-
"""Калибровка лексикографического порядка целей.

Постановщик на прямой вопрос о конфликте критериев ответил: «Больше выполненных
заявок — это основной критерий, а второй по приоритету — меньше исполнителей».
Отсюда порядок: максимум заявок -> минимум исполнителей -> минимум пробега.

Порядок обеспечивается разделением МАСШТАБОВ в одной целевой функции.
Единица измерения всей функции — метр. Числа подобраны так, чтобы слой ниже
никогда не мог перевесить слой выше; это проверяется в tests/test_weights.py.
"""
# Слой 3 (метры): типичный маршрут 20-40 км, худший в Подмосковье ~300 км.
MAX_ROUTE_M = 400_000

# Слой 2: одна задействованная бригада дороже, чем весь пробег плана.
# Граница именно такая, а не «дороже одного маршрута»: выигрыш от лишней бригады
# по расстоянию ограничен пробегом ВСЕГО плана, то есть MAX_ROUTE_M на каждую из
# бригад. При парке 15 это 6 000 000, и 5 000 000 границу бы не удержали: слой
# «пробег» мог бы перевесить слой «исполнители». Проверяется tests/test_weights.py.
VEHICLE_COST = 10_000_000


# Слой 1: брошенная заявка дороже, чем весь парк вместе с его пробегом.
def drop_penalty(n_vehicles: int) -> int:
    return n_vehicles * VEHICLE_COST + n_vehicles * MAX_ROUTE_M + 10_000_000


# Приоритет распределения (разъяснение экспертов от 19.09):
# Авария -> Подключение -> Ремонт/Дозаказ. Если ресурса не хватает на всё,
# бросать надо низкоприоритетное, а не что попало. Множитель применяется к штрафу
# за неназначение, поэтому даже самая дешёвая заявка остаётся дороже бригады.
PRIORITY_MULT = {1: 4, 2: 2, 3: 1}

# Аварию нужно закрыть как можно раньше. Для заявок с окном на все сутки ставим
# мягкую границу в начало окна доступности: каждая минута ожидания стоит немного,
# и при прочих равных авария уезжает в начало дня. Слой не спорит ни с одним выше:
# даже 13 часов задержки дешевле одной бригады.
EMERGENCY_ASAP_PENALTY_PER_MIN = 300

# Опоздание. В статическом плане не используется (окна жёсткие), включается только
# при перепланировании. Должно быть заметно НИЖЕ стоимости бригады: иначе солвер
# добавит человека ради двух минут опоздания и испортит главную метрику.
LATE_PENALTY_PER_MIN = 50_000

# Штраф за изменение уже озвученного клиенту назначения при перепланировании.
# Заметно больше типичного плеча (3-7 км), иначе «минимальные изменения» не удержат
# ни одного назначения и разница «до/после» превратится в кашу. И заметно меньше
# стоимости бригады, иначе переназначение станет невозможным.
STABILITY_PENALTY = 30_000
