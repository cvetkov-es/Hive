// Цвет бригады на карте и ленте смены.
//
// Порядок оттенков фиксирован и не генерируется: девятая бригада не получает
// «следующий вычисленный цвет», она берёт первый слот заново, но с ДРУГОЙ
// формой маркера. Причина не в эстетике — она измерена. На карте видны все
// пары цветов сразу, и по всем парам проходят только три слота: проверка
// палитры даёт для первой тройки худшую пару с ΔE 9.2 при дальтонизме, а с
// четвёртого слота жёлтый и оранжевый оказываются рядом и валятся ниже порога.
// Пятнадцать различимых оттенков не существует, сколько их ни подбирай.
//
// Поэтому опознание бригады держится не на цвете:
//   * выбор — выбранная бригада горит, остальные гаснут;
//   * форма — четыре формы поверх восьми оттенков, то есть 32 метки;
//   * подпись — список бригад служит легендой, наведение даёт имя.
// Цвет остаётся подсказкой, а не единственным признаком.

export const SERIES = [
  '#2a78d6', // синий
  '#eb6834', // оранжевый
  '#1baf7a', // бирюзовый
  '#eda100', // жёлтый
  '#e87ba4', // маджента
  '#008300', // зелёный
  '#4a3aa7', // фиолетовый
  '#e34948', // красный
] as const;

export type MarkShape = 'ci' | 'sq' | 'di' | 'tr';
const SHAPES: MarkShape[] = ['ci', 'sq', 'di', 'tr'];

// Состояния зарезервированы и в палитру бригад не попадают.
export const STATE = {
  unassigned: '#b3261e',
  emergency: '#a86e08',
  frozen: '#8798a5',
  ghost: '#8798a5',
} as const;

export type Mark = { color: string; shape: MarkShape };

/** Метка бригады по её месту в парке. Место берётся из порядка списка бригад,
 *  а не из позиции в плане: цвет обязан следовать за бригадой, а не за её
 *  местом в рейтинге, иначе фильтр «показать занятых» перекрасит выживших. */
export function markOf(index: number): Mark {
  return {
    color: SERIES[index % SERIES.length],
    shape: SHAPES[Math.floor(index / SERIES.length) % SHAPES.length],
  };
}

/** Индексы бригад фиксируются один раз на регион. */
export function buildMarks(engineerIds: string[]): Record<string, Mark> {
  const out: Record<string, Mark> = {};
  engineerIds.forEach((id, i) => { out[id] = markOf(i); });
  return out;
}

