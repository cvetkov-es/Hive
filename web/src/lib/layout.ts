// Какая раскладка пульта помещается в окно.
//
// A («wide») — карта во весь экран, панели плавают поверх: слева бригады
// (340 px), справа объяснение (380 px), снизу лента смены. Ей нужно место:
// при меньшей ширине боковые панели закрывают почти всю карту, при меньшей
// высоте — лента. Тогда B («compact»): карта сверху, под ней бригады, слитые
// с лентой, объяснение справа колонкой.
//
// Порог проверен на размерах, которые встретятся на показе: 1366×768 — B,
// 1536×864 (ноутбук 1920×1080 с масштабом 125 %) и больше — A.

export type Layout = 'wide' | 'compact';

export const WIDE_MIN_WIDTH = 1440;
export const WIDE_MIN_HEIGHT = 820;

export function layoutFor(width: number, height: number): Layout {
  return width >= WIDE_MIN_WIDTH && height >= WIDE_MIN_HEIGHT ? 'wide' : 'compact';
}
